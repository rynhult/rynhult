"""G1 Claude extension of g56's G5 OS SIGKILL/wait/restart controller.

The native model and disposable account namespace outlive both real OS workers.
The separate main uses the G5 typed NodeLink and production HA Authority.
"""
import asyncio
import json
import os
import sys
from pathlib import Path


async def rpc(path, method):
    reader, writer = await asyncio.open_unix_connection(path)
    try:
        writer.write(json.dumps({'method': method}).encode() + b'\n')
        await writer.drain()
        value = json.loads(await asyncio.wait_for(reader.readline(), 30))
        if 'error' in value:
            raise RuntimeError(value)
        return value
    finally:
        writer.close()
        await writer.wait_closed()


def native_tui(settings, env, observer_file, requests, native):
    # env was generated by probe.sandbox/claude_resume, never inherited account data.
    assert env['ANTHROPIC_API_KEY'] == 'relay-synthetic-fixture-only'
    Path('/evidence/restart-env.json').write_text(json.dumps(env))
    Path('/evidence/restart-env.json').chmod(0o600)
    before = len(requests)
    return {**asyncio.run(controller(requests)), 'requests_before': before, 'requests_after': len(requests)}


async def worker():
    # Reuse the production-placement native broker fixture, adding only loss
    # injection after durable proof. No producer/guard/authority result is faked.
    import placement_broker

    from acc.broker.relay_ownership import ExclusiveRuntime
    original_handle, original_publish = ExclusiveRuntime.handle, ExclusiveRuntime.publish
    original_persist = ExclusiveRuntime.persist_application
    data = json.loads(Path('/evidence/placement-config.json').read_text())
    async def persist(self, value, result):
        if data.get('before_proof') and result.get('outcome') == 'accepted':
            Path('/evidence/application-seen').touch()
            await asyncio.Event().wait()  # OS broker SIGKILL at the pre-fsync boundary
        await original_persist(self, value, result)
    async def handle(self, method, params):
        if method == 'owner.answer':
            fd = os.open('/evidence/answer-invocations', os.O_WRONLY | os.O_CREAT | os.O_APPEND, 0o600)
            try:
                os.write(fd, b'answer\n')
                os.fsync(fd)
            finally:
                os.close(fd)
        result = await original_handle(self, method, params)
        if method == 'owner.answer' and result.get('outcome') == 'accepted':
            Path('/evidence/application-ready').touch()
            return {'outcome': 'unknown'}  # withheld reply; original fact already fsynced
        return result
    async def publish(self, value):
        if value.get('kind') == 'decision.applied':
            Path('/evidence/application-ready').touch()
            raise ConnectionError('Fixture publication withheld before OS crash')
        return await original_publish(self, value)
    ExclusiveRuntime.handle, ExclusiveRuntime.publish = handle, publish
    ExclusiveRuntime.persist_application = persist
    await placement_broker.serve(json.loads(Path('/evidence/restart-env.json').read_text()))


async def controller(requests):
    os.sched_setaffinity(0, set(sorted(os.sched_getaffinity(0))[:8]))
    data = json.loads(Path('/evidence/placement-config.json').read_text())
    processes = {}
    killed_main = False
    tracked = []
    async def start(name):
        endpoint = '/evidence/main.sock' if name == 'main' else '/evidence/owned-inspect.sock'
        Path(endpoint).unlink(missing_ok=True)
        if name == 'broker':
            Path('/evidence/owned-broker.sock').unlink(missing_ok=True)
        args = [sys.executable, '/evidence/application_restart_worker.py'] if name == 'main' else [sys.executable, '/evidence/application_restart_fixture.py', '--worker']
        process = await asyncio.create_subprocess_exec(*args, stdin=asyncio.subprocess.DEVNULL, stdout=asyncio.subprocess.DEVNULL)
        processes[name] = process
        for _ in range(1000):
            assert process.returncode is None, (name, process.returncode)
            if Path(endpoint).exists():
                return process.pid
            await asyncio.sleep(.02)
        raise TimeoutError(name)
    await start('broker')
    finished = asyncio.Event()
    async def inspect(reader, writer):
        nonlocal killed_main
        try:
            method = json.loads(await reader.readline())['method']
            if method in ('main_start', 'broker_start'):
                name = method.split('_')[0]
                assert name not in processes or processes[name].returncode is not None
                result = {'pid': await start(name)}
            elif method in ('main_kill', 'broker_kill'):
                name = method.split('_')[0]
                process = processes[name]
                state = await rpc('/evidence/owned-inspect.sock', 'state')
                if state.get('owner_process'):
                    tracked.append(state['owner_process'])
                process.kill()
                await process.wait()  # real G5 fencing receipt, not cache reset
                killed_main |= name == 'main'
                result = {'pid': process.pid, 'returncode': process.returncode}
            elif method.startswith('main:'):
                action = method.removeprefix('main:')
                if action == 'promote_fenced':
                    assert killed_main
                result = await rpc('/evidence/main.sock', action)
            elif method.startswith('broker:'):
                result = await rpc('/evidence/owned-inspect.sock', method.removeprefix('broker:'))
            elif method == 'state':
                result = await rpc('/evidence/owned-inspect.sock', 'state')
                result['model_requests'] = len(requests)
                result['model_inferences'] = sum('count_tokens' not in row['path'] for row in requests)
                result['old_execution'] = []
                for identity in tracked:
                    pid, started = identity.split(':')[:2]
                    path = Path('/proc') / pid / 'stat'
                    if path.exists():
                        fields = path.read_text().rsplit(')', 1)[1].split()
                        if fields[19] == started and fields[0] != 'Z':
                            result['old_execution'].append(identity)
                result['application_seen'] = Path('/evidence/application-seen').exists()
                result['proof_ready'] = Path('/evidence/application-ready').exists()
                result['answer_invocations'] = len(Path('/evidence/answer-invocations').read_text().splitlines()) if Path('/evidence/answer-invocations').exists() else 0
                result['broker_pid'] = processes['broker'].pid
            elif method == 'finish':
                result = {'finished': True}
                finished.set()
            else:
                raise ValueError(method)
        except Exception as error:
            result = {'error': repr(error)}
        writer.write(json.dumps(result).encode() + b'\n')
        await writer.drain()
        writer.close()
        await writer.wait_closed()
    server = await asyncio.start_unix_server(inspect, '/evidence/restart-inspect.sock')
    Path('/evidence/restart-ready').touch()
    try:
        await asyncio.wait_for(finished.wait(), data.get('timeout', 180))
        return {'terminalMediated': False, 'broker_pid': processes['broker'].pid}
    finally:
        for process in processes.values():
            if process.returncode is None:
                process.terminate()
                await process.wait()
        server.close()
        await server.wait_closed()


if __name__ == '__main__':
    asyncio.run(worker())
